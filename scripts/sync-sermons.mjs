import { readFile, writeFile, rename, unlink } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { sermons } from '../sermon-data.js';
import { CHANNEL_ID, CHANNEL_URL, parseChannelPage, parseFeed, mergeSermons } from './youtube-parser.mjs';
const destination=fileURLToPath(new URL('../sermon-data.js',import.meta.url));
async function request(url){
  const response=await fetch(url,{headers:{'User-Agent':'Mozilla/5.0 (compatible; GoodShepherdWebsite/1.0)','Accept-Language':'zh-TW,zh;q=0.9,en;q=0.8'},signal:AbortSignal.timeout(25000)});
  if(!response.ok)throw new Error(`HTTP ${response.status}`);
  const body=await response.text();if(body.length>12_000_000)throw new Error('Unexpected response size');return body;
}
try {
  let entries;
  const inputIndex=process.argv.indexOf('--input');
  if(inputIndex!==-1){if(!process.argv[inputIndex+1])throw new Error('--input requires a local HTML file');entries=parseChannelPage(await readFile(process.argv[inputIndex+1],'utf8'));}
  else {
    try{entries=parseChannelPage(await request(CHANNEL_URL));if(!entries.length)throw new Error('No qualifying entries in channel page');}
    catch(error){console.warn(`Channel page unavailable: ${error.message}; trying public RSS.`);entries=parseFeed(await request(`https://www.youtube.com/feeds/videos.xml?channel_id=${CHANNEL_ID}`));}
  }
  const updated=mergeSermons(sermons,entries);
  if(process.argv.includes('--dry-run')){console.log(JSON.stringify(updated.map(s=>({id:s.id,date:s.date,title:s.title['zh-Hant']})),null,2));}
  else if(JSON.stringify(updated)===JSON.stringify(sermons))console.log('Sermons already current.');
  else {
    const output=`// Generated by npm run sync:sermons. Do not edit by hand.\n// Source: ${CHANNEL_URL}\n// Existing editorial translations are retained; new titles use the original channel wording.\nexport const sermons = ${JSON.stringify(updated,null,2)};\n`;
    await writeFile(`${destination}.tmp`,output,'utf8');await rename(`${destination}.tmp`,destination);
    console.log(`Synchronized ${entries.length} qualifying channel videos; ${updated.length} sermons retained.`);
  }
} catch(error){await unlink(`${destination}.tmp`).catch(()=>{});console.error(`Sync failed; existing sermon list unchanged. ${error.message}`);process.exitCode=1;}
